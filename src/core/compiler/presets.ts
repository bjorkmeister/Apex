import { createEmptyLedger, postJournal } from "../engine/ledger";
import type { Cents, WorldState } from "../schema";

export type ScenarioPresetId =
  | "vertical_farm"
  | "custom_ebike"
  | "cold_chain_logistics";

export interface ScenarioPresetMeta {
  id: ScenarioPresetId;
  name: string;
  industry: string;
  tagline: string;
  summary: string;
  build: (seed?: number) => WorldState;
}

/**
 * Reconcile initial balance sheet accounts (`cash`, `inventory_raw`, `inventory_finished`,
 * `ppe_gross`, `revolver`, `term_debt`, `paid_in_capital`) from the physical lots, fixed assets,
 * and debt facilities so Tick 0 starts with `Trial Balance === 0` and `Assets === Liabilities + Equity`.
 */
export function initializeOpeningBalanceSheet(
  state: WorldState,
  openingCash: Cents,
): WorldState {
  state.finance.ledger = createEmptyLedger();

  let rawVal: Cents = 0;
  let finVal: Cents = 0;
  for (const lot of state.warehouses.lots) {
    const item = state.catalog.items.find((i) => i.id === lot.itemId);
    if (item?.kind === "finished") finVal += lot.value;
    else rawVal += lot.value;
  }

  const ppeVal: Cents = state.finance.fixedAssets.reduce((s, f) => s + f.cost, 0);
  const revolverVal: Cents = state.finance.debts
    .filter((d) => d.kind === "revolver")
    .reduce((s, d) => s + d.principal, 0);
  const termDebtVal: Cents = state.finance.debts
    .filter((d) => d.kind !== "revolver")
    .reduce((s, d) => s + d.principal, 0);

  const totalAssets = openingCash + rawVal + finVal + ppeVal;
  const totalDebt = revolverVal + termDebtVal;
  const paidInCapital = totalAssets - totalDebt;

  postJournal(state, {
    memo: "Opening balance sheet capitalization",
    source: "compiler:init",
    cashFlow: "financing",
    lines: [
      { account: "cash", amount: openingCash },
      ...(rawVal > 0 ? [{ account: "inventory_raw" as const, amount: rawVal }] : []),
      ...(finVal > 0 ? [{ account: "inventory_finished" as const, amount: finVal }] : []),
      ...(ppeVal > 0 ? [{ account: "ppe_gross" as const, amount: ppeVal }] : []),
      ...(revolverVal > 0 ? [{ account: "revolver" as const, amount: -revolverVal }] : []),
      ...(termDebtVal > 0 ? [{ account: "term_debt" as const, amount: -termDebtVal }] : []),
      { account: "paid_in_capital", amount: -paidInCapital },
    ],
  });

  // Opening cash is the baseline before Tick 1 cash flows
  state.finance.periodStartCash = openingCash;
  state.finance.periodCashFlow = { operating: 0, investing: 0, financing: 0 };

  if (state.finance.equity.capTable.length > 0) {
    state.finance.equity.capTable[0].invested = Math.max(0, paidInCapital);
  }

  return state;
}

